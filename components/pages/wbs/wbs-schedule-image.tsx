import { forwardRef } from "react";
import type { Artifact } from "@/lib/artifact-types";
import { taskMetrics } from "@/lib/integration";
import "./wbs-schedule-image.css";

export type WbsScheduleItem = { task: Artifact; depth: number };

type WbsScheduleImageProps = {
  artifacts: Artifact[];
  tasks: Artifact[];
  ordered: WbsScheduleItem[];
  firstDate: string;
  lastDate: string;
  first: number;
  span: number;
};

export const WbsScheduleImage = forwardRef<
  HTMLDivElement,
  WbsScheduleImageProps
>(function WbsScheduleImage(
  { artifacts, tasks, ordered, firstDate, lastDate, first, span },
  ref,
) {
  const metrics = ordered.map(({ task }) => taskMetrics(artifacts, task));
  const effortMetrics = metrics.filter(
    (_, index) => ordered[index].task.fields.taskType !== "요약",
  );
  const plannedEffort = effortMetrics.reduce(
    (sum, item) => sum + item.plannedEffort,
    0,
  );
  const actualEffort = effortMetrics.reduce(
    (sum, item) => sum + item.actualEffort,
    0,
  );
  const progress = metrics.length
    ? Math.round(
        metrics.reduce((sum, item) => sum + item.progress, 0) / metrics.length,
      )
    : 0;

  return (
    <div className="wbs-image-stage" aria-hidden="true">
      <div ref={ref} className="wbs-image-document">
        <header className="wbs-image-header">
          <div>
            <span className="wbs-image-eyebrow">PROJECT SCHEDULE</span>
            <h1>WBS 일정과 공수</h1>
            <p>
              {firstDate} — {lastDate}
            </p>
          </div>
          <span className="wbs-image-mark">HAMS MATRIX</span>
        </header>

        <div className="wbs-image-summary">
          <div>
            <span>전체 작업</span>
            <strong>{ordered.length}</strong>
          </div>
          <div>
            <span>계획 공수</span>
            <strong>{plannedEffort}h</strong>
          </div>
          <div>
            <span>실제 공수</span>
            <strong>{actualEffort}h</strong>
          </div>
          <div>
            <span>평균 진척률</span>
            <strong>{progress}%</strong>
          </div>
        </div>

        <table className="wbs-image-table">
          <thead>
            <tr>
              <th>작업 / 코드</th>
              <th>단계</th>
              <th>계획 기간</th>
              <th>일정</th>
              <th>선행 작업</th>
              <th>계획 / 실제</th>
              <th>진척률</th>
            </tr>
          </thead>
          <tbody>
            {ordered.map(({ task, depth }, index) => {
              const item = metrics[index];
              const left = ((Date.parse(task.fields.startDate) - first) / span) * 100;
              const width =
                ((Date.parse(task.fields.endDate) -
                  Date.parse(task.fields.startDate) +
                  86400000) /
                  span) *
                100;
              return (
                <tr key={task.id}>
                  <td>
                    <span
                      className="wbs-image-task"
                      style={{ paddingInlineStart: depth * 14 }}
                    >
                      <b>{task.code}</b>
                      {task.title}
                    </span>
                  </td>
                  <td>{task.fields.phase}</td>
                  <td className="wbs-image-date">
                    {task.fields.startDate} — {task.fields.endDate}
                  </td>
                  <td>
                    <div className="wbs-image-track">
                      <div
                        className="wbs-image-bar"
                        style={{ left: `${left}%`, width: `${width}%` }}
                      >
                        <i style={{ width: `${item.progress}%` }} />
                      </div>
                    </div>
                  </td>
                  <td>
                    {task.structure?.dependencies
                      ?.map((id) => tasks.find((candidate) => candidate.id === id)?.code)
                      .filter(Boolean)
                      .join(", ") || "—"}
                  </td>
                  <td>
                    {item.plannedEffort}h / {item.actualEffort}h
                  </td>
                  <td>
                    <strong className="wbs-image-progress">{item.progress}%</strong>
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>

        <footer className="wbs-image-footer">
          <span>진행률 막대의 진한 영역은 완료된 작업 비율입니다.</span>
          <span>Generated by HAMS Matrix</span>
        </footer>
      </div>
    </div>
  );
});
